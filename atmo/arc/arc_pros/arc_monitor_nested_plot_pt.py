#-----------------------------------------------------------------------------------------

# ------ SETUP ---------------------------------------------
Fe_H = 1      # Metallicity for condensation curves
xmin = 500    # temperature minimum
xmax = 2000    # temperature maximum
ymin = 5E0     # presure maximum plotted
#-----------------------------------------------------------------------------------------

#-----------------------------------------------------------------------------------------
# Read in path argument.  If absent use current directory
print('Number of arguments:', len(sys.argv), 'arguments.')
print('Argument List:', str(sys.argv))
if len(sys.argv) > 1:
    dirs=sys.argv[1]
else:
    dirs='./'
print('Working in Directory: ',dirs)
#-----------------------------------------------------------------------------------------


#-----------------------------------------------------------------------------------------
# Read in IDL save file
list=glob.glob(dirs+"*.MULTINEST.sav")
number_of_images=len(list)         #Count number of images

sav = readsav(os.path.join(list[0]))
print('Reading in File: ',list[0])

#>>> print(sav.keys())
#dict_keys(['multinest_str', 'nestpars', 'lp', 'log_likelihood_func', 'prior_func', 'num_params', 'num', 'sample_num', 'expand', 'tol', 'tofit'])
#multinest_str is an IDL structure, rest are normal arrays
multinest_str = sav['multinest_str']
nestpars=sav['nestpars']

#Show the variables in the multinest_str structure
#>>> multinest_str.dtype.names  
#('SAMPLES', 'LOG_PROB', 'LOGZ', 'LOGZ_ERR', 'H', 'SAMPLES_MODEL', 'SAMPLES_ABUNDANCES', 'SAMPLES_TEMPERATURE', 'WS', 'PRESSURE', 'X', 'Y', 'ERR', 'WAVERR', 'MOLNAME')

pressure   =multinest_str['PRESSURE'][0]*1E-6       # barye -> bar 
temperature=multinest_str['SAMPLES_TEMPERATURE'][0] # for IDL structures, there is an extra array ontop of the variable you need to get rid of, so select [0]
prob=np.exp(multinest_str['LOG_PROB'][0])
#-----------------------------------------------------------------------------------------

#-----------------------------------------------------------------------------------------
# Generate Posterior
#
# Define Temperature posterior 1,2,3-sigma arrays
tmed=pressure/pressure
t1l=pressure/pressure
t1h=pressure/pressure
t2l=pressure/pressure
t2h=pressure/pressure
t3l=pressure/pressure
t3h=pressure/pressure

# Posterior is generated by selecting a pressure level,
# sorting the dead+live sample values, sorting the associated probability for each sample with the same indicies,
# making the cummulative distribution of the probability, and selecting relevent 1,2,3 sigma values from the cummulative distribution.
number_of_bins=pressure.size
for bin in range(0,number_of_bins):     #Loop over each pressure level
    #sort parameters
    srt=np.argsort(temperature[:,bin])  # sort temperatures at one pressure level, index
    parameter=temperature[srt,bin]      # sort temperatures at one pressure level
    parameter_prob=prob[srt]            # probability sorted with increasing temperature
    #weighted average parmaeter value
    w_ave=np.sum(parameter*parameter_prob) 
    #print(w_ave)
    value=0.5
    absolute_val_array = np.abs(np.cumsum(parameter_prob) - value)
    smallest_difference_index = absolute_val_array.argmin()
    #print(parameter[smallest_difference_index])
    medpar=parameter[smallest_difference_index]
    #Calculate 1,2,3 sigma intervals from cummulative distribution of probability which has sorted by the parameter value
    smallest_difference_index=np.abs(np.cumsum(parameter_prob) - 0.5E0+0.68268E0/2.).argmin()
    el=(parameter[smallest_difference_index])
    smallest_difference_index=np.abs(np.cumsum(parameter_prob) - 0.5E0-0.68268E0/2.).argmin()
    eh=(parameter[smallest_difference_index])
    smallest_difference_index=np.abs(np.cumsum(parameter_prob) - 0.5E0+0.95449E0/2.).argmin()
    e2l=(parameter[smallest_difference_index])
    smallest_difference_index=np.abs(np.cumsum(parameter_prob) - 0.5E0-0.95449E0/2.).argmin()
    e2h=(parameter[smallest_difference_index])
    smallest_difference_index=np.abs(np.cumsum(parameter_prob) - 0.5E0+0.99730E0/2.).argmin()
    e3l=(parameter[smallest_difference_index])
    smallest_difference_index=np.abs(np.cumsum(parameter_prob) - 0.5E0-0.99730E0/2.).argmin()
    e3h=(parameter[smallest_difference_index])
    #save values to arrays
    tmed[bin]=medpar
    t1l[bin]=el
    t1h[bin]=eh
    t2l[bin]=e2l
    t2h[bin]=e2h
    t3l[bin]=e3l
    t3h[bin]=e3h
#-----------------------------------------------------------------------------------------
#plot


plot(tmed,pressure,label='T-P Mean',color='indigo',linewidth=3)  #overplot Transit model at data
matplotlib.pyplot.fill_betweenx(pressure,t1l,t1h,facecolor='cornflowerblue',alpha=0.65,label='T-P 1$-\sigma$')
matplotlib.pyplot.fill_betweenx(pressure,t2l,t2h,facecolor='cornflowerblue',alpha=0.4,label='T-P 2$-\sigma$')
matplotlib.pyplot.fill_betweenx(pressure,t3l,t3h,facecolor='cornflowerblue',alpha=0.2,label='T-P 3$-\sigma$')

yscale('log')
gca().invert_yaxis()
ylabel('Pressure (bar)')
xlabel('Temperature (K)')
axes().xaxis.set_minor_locator(MultipleLocator(50))
_ = ylim(ymin,pressure.min())
_ = xlim(xmin,xmax)


#Setup Pressure Scale
pmin=-6   # log_10 minimum pressure
pmax=3    # log_10 maximum pressure
spacing = np.arange(pmin,pmax,0.1)
log_pressure_bar=spacing
pressure_bar = ( 10 ** spacing )
pressure_barye = ( 10 ** spacing )*1e6
#---------------------------------------------------------

#Plot CO/CH4 Gas Equilbrium
TCH4_CO = 1E4/( (-12/7E0)*log_pressure_bar+8.5+0.83*Fe_H) #approximated from Lodders & Fegley 2002 Fig 4.
plot(TCH4_CO,pressure_bar, linestyle='dotted',label='CO=CH$_4$',alpha=0.8,color='black')

#Plot Condensation Curves
#;Al
Tcond_Al2O3     = 1E4/(5.014 - 0.2179*log_pressure_bar + 2.264E-3*log_pressure_bar**2 - 0.580*Fe_H)
plot(Tcond_Al2O3,pressure_bar, linestyle='dashed',label='Al$_2$O$_3$',alpha=0.8)

#;Ca
Tcond_Ca3Ti2O7  = 1E4/(5.114 - 0.284*log_pressure_bar - 0.568*Fe_H)
Tcond_Ca4Ti3O10 = 1E4/(5.113 - 0.281*log_pressure_bar - 0.563*Fe_H)
Tcond_CaTiO3    = 1E4/(5.125 - 0.277*log_pressure_bar - 0.554*Fe_H)
plot(Tcond_CaTiO3,pressure_bar, linestyle='dashed',label='CaTiO$_3$',alpha=0.8)
plot(Tcond_Ca4Ti3O10,pressure_bar, linestyle='dashed',label='Ca$_4$Ti$_3$O$_{10}$',alpha=0.8)
plot(Tcond_Ca3Ti2O7,pressure_bar, linestyle='dashed',label='Ca$_3$Ti$_2$O$_7$',alpha=0.8)

#;Fe
Tcond_Fe         =1E4/(5.44 - 0.48*log_pressure_bar - 0.48*Fe_H)
plot(Tcond_Fe,pressure_bar, linestyle='dashed',label='Fe',alpha=0.8)

#;Mg
Tcond_Mg2SiO4   = 1E4/(5.89  - 0.37*log_pressure_bar - 0.73*Fe_H)
plot(Tcond_Mg2SiO4,pressure_bar, linestyle='dashed',label='Mg$_2$SiO$_4$',alpha=0.8)
Tcond_MgSiO3    = 1E4/(6.26  - 0.35*log_pressure_bar - 0.70*Fe_H)
plot(Tcond_MgSiO3,pressure_bar, linestyle='dashed',label='MgSiO$_3$',alpha=0.8)

#;MgS
Tcond_MgS       = 1E4/(7.45  - 0.42*log_pressure_bar - 0.841*Fe_H)
plot(Tcond_MgS,pressure_bar, linestyle='dashed',label='MgS',alpha=0.8)

#;Na2S
Tcond_Na2S      = 1E4/(10.5-0.72*log_pressure_bar-1.08*Fe_H)
plot(Tcond_Na2S,pressure_bar, linestyle='dashed',label='Na$_2$S',alpha=0.8)

#KCL
Tcond_KCL      = 1E4/(12.479-0.879*log_pressure_bar-1.08*Fe_H)
if xmin < 1000: plot(Tcond_KCL,pressure_bar, linestyle='dashed',label='KCL',alpha=0.8)

#;ZnS
Tcond_ZnS       = 1E4/(12.52 - 0.63*log_pressure_bar - 1.26*Fe_H)
if xmin < 1000: plot(Tcond_ZnS,pressure_bar, linestyle='dashed',label='ZnS',alpha=0.8)
    
#;H2O
Tcond_H2O       = 1E4/(38.84 - 3.93*Fe_H - 3.83*log_pressure_bar - 0.20*Fe_H*log_pressure_bar)
if xmin < 400: plot(Tcond_H2O,pressure_bar, linestyle='dashed',label='H$_2$O',alpha=0.8)

##---------------------------------------------------------

rcParams["legend.loc"] = 'upper right' 
legend(fontsize='x-small')
